//! Synthetic STDF generator for demos and tests: made-up data, never from a tester.
//! Produces realistic wafer-sort data: multi-site, correlated parametrics, a site
//! offset, radial wafer gradient, a few outlier dies, MPR and FTR records, and
//! HBR/SBR/PCR summaries; and looped final-test touchdown files.
//!
//! With [`Profile::Tc`] the files follow the custom test-cell (TC) STDF profile: per
//! site and summary PCR/HBR/SBR/TSR, PGR and PLR beside PMR, base units with
//! RES_SCAL, `name_value;` part text, filled MIR/SDR fields and the GDR.MIR_ADD,
//! GDR.AUTOMATION and (wafer sort) GDR.REF_DIE records.

use crate::stdf::codec::GenData;
use crate::stdf::*;
use anyhow::{bail, Result};
use rand::{Rng, SeedableRng};
use rand_distr::{Distribution, Normal};
use std::collections::BTreeMap;
use std::path::Path;

/// Which STDF profile a synthetic file follows.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Profile {
    /// the records stdf-cypher's own tests use (unchanged files)
    #[default]
    Plain,
    /// the custom test-cell (TC) STDF profile
    Tc,
}

impl Profile {
    pub fn parse(s: &str) -> Result<Profile> {
        match s.trim().to_ascii_lowercase().as_str() {
            "" | "plain" => Ok(Profile::Plain),
            "tc" => Ok(Profile::Tc),
            o => bail!("profile '{o}': use plain or tc"),
        }
    }
}

/// What every TC-profile file says about itself: the data is made up.
const SYNTHETIC_NOTE: &str = "SYNTHETIC DATA: generated by stdf-cypher, not from a tester";

/// One test on one site, for its TSR.
#[derive(Default, Clone)]
struct TestTally {
    exec: u32,
    fail: u32,
    alarm: u32,
    n: u32,
    min: f64,
    max: f64,
    sum: f64,
    sqr: f64,
}

/// Counts for the summary records of a TC-profile file: per site and in total.
#[derive(Default)]
struct Tally {
    /// (site, bin) -> parts
    hbin: BTreeMap<(u8, u16), u32>,
    sbin: BTreeMap<(u8, u16), u32>,
    /// bin -> (name, P/F)
    hname: BTreeMap<u16, (String, char)>,
    sname: BTreeMap<u16, (String, char)>,
    /// site -> (parts, good)
    parts: BTreeMap<u8, (u32, u32)>,
    /// (test, site) -> tally
    tests: BTreeMap<(u32, u8), TestTally>,
    /// test -> (type P/M/F, name)
    test_info: BTreeMap<u32, (char, String)>,
}

impl Tally {
    #[allow(clippy::too_many_arguments)]
    fn part(&mut self, site: u8, hb: u16, hname: &str, sb: u16, sname: &str, good: bool) {
        let pf = if good { 'P' } else { 'F' };
        *self.hbin.entry((site, hb)).or_default() += 1;
        *self.sbin.entry((site, sb)).or_default() += 1;
        self.hname.entry(hb).or_insert_with(|| (hname.to_string(), pf));
        self.sname.entry(sb).or_insert_with(|| (sname.to_string(), pf));
        let e = self.parts.entry(site).or_default();
        e.0 += 1;
        e.1 += u32::from(good);
    }

    /// One execution of a test: `values` as logged (several for a multi-pin test, none for a
    /// functional test).
    #[allow(clippy::too_many_arguments)]
    fn result(&mut self, num: u32, typ: char, name: &str, site: u8, values: &[f64], fail: bool, alarm: bool) {
        self.test_info.entry(num).or_insert_with(|| (typ, name.to_string()));
        let t = self.tests.entry((num, site)).or_default();
        t.exec += 1;
        t.fail += u32::from(fail);
        t.alarm += u32::from(alarm);
        for &v in values {
            if t.n == 0 {
                (t.min, t.max) = (v, v);
            }
            t.n += 1;
            t.min = t.min.min(v);
            t.max = t.max.max(v);
            t.sum += v;
            t.sqr += v * v;
        }
    }

    /// TSR, HBR, SBR and PCR for every site, then the summary of all sites (head and site 255).
    fn write(&self, w: &mut StdfWriter) -> Result<()> {
        let sites: Vec<u8> = self.parts.keys().copied().collect();
        for (&num, (typ, name)) in &self.test_info {
            let mut all = TestTally::default();
            let mut rows: Vec<(u8, u8, TestTally)> = vec![];
            for &site in &sites {
                let Some(t) = self.tests.get(&(num, site)) else { continue };
                all.exec += t.exec;
                all.fail += t.fail;
                all.alarm += t.alarm;
                if t.n > 0 {
                    if all.n == 0 {
                        (all.min, all.max) = (t.min, t.max);
                    }
                    all.n += t.n;
                    all.min = all.min.min(t.min);
                    all.max = all.max.max(t.max);
                    all.sum += t.sum;
                    all.sqr += t.sqr;
                }
                rows.push((1, site, t.clone()));
            }
            rows.push((255, 255, all));
            for (head, site, t) in rows {
                // OPT_FLAG: bit 2 = no test time; bits 0, 1, 4, 5 = no min, max, sums, squares
                let opt_flag = if t.n > 0 { 0x04 } else { 0x37 };
                w.write(&Record::TSR(Tsr {
                    head_num: head,
                    site_num: site,
                    test_typ: *typ,
                    test_num: num,
                    exec_cnt: t.exec,
                    fail_cnt: t.fail,
                    alrm_cnt: t.alarm,
                    test_nam: name.clone(),
                    opt_flag,
                    test_min: t.min as f32,
                    test_max: t.max as f32,
                    tst_sums: t.sum as f32,
                    tst_sqrs: t.sqr as f32,
                    ..Default::default()
                }))?;
            }
        }
        for (hard, counts, names) in [(true, &self.hbin, &self.hname), (false, &self.sbin, &self.sname)] {
            let mut total: BTreeMap<u16, u32> = BTreeMap::new();
            let mut rows: Vec<(u8, u8, u16, u32)> = vec![];
            for (&(site, bin), &c) in counts {
                *total.entry(bin).or_default() += c;
                rows.push((1, site, bin, c));
            }
            rows.extend(total.into_iter().map(|(bin, c)| (255, 255, bin, c)));
            for (head, site, bin, c) in rows {
                let (name, pf) = names.get(&bin).cloned().unwrap_or_default();
                let b = Bin {
                    head_num: head,
                    site_num: site,
                    bin_num: bin,
                    bin_cnt: c,
                    bin_pf: pf,
                    bin_nam: name,
                };
                w.write(&if hard { Record::HBR(b) } else { Record::SBR(b) })?;
            }
        }
        let (mut cnt, mut good) = (0u32, 0u32);
        for (&site, &(c, g)) in &self.parts {
            cnt += c;
            good += g;
            w.write(&Record::PCR(Pcr {
                head_num: 1,
                site_num: site,
                part_cnt: c,
                good_cnt: g,
                ..Default::default()
            }))?;
        }
        w.write(&Record::PCR(Pcr {
            head_num: 255,
            site_num: 255,
            part_cnt: cnt,
            good_cnt: good,
            ..Default::default()
        }))?;
        Ok(())
    }
}

/// A GDR of text fields: the record's name, then `KEY=value` pairs. The profile names these
/// GDRs but the field layout used here is an assumption: check it against the full profile.
fn gdr(w: &mut StdfWriter, name: &str, fields: &[(&str, String)]) -> Result<()> {
    let mut gen_data = vec![GenData::Cn(name.to_string())];
    gen_data.extend(fields.iter().map(|(k, v)| GenData::Cn(format!("{k}={v}"))));
    w.write(&Record::GDR(Gdr { gen_data }))?;
    Ok(())
}

/// The MIR fields a TC-profile file fills in, on top of the ones every file has.
fn tc_mir(mir: &mut Mir, flow: &str, retest: bool, final_test: bool) {
    mir.cmod_cod = if retest { 'R' } else { 'T' };
    mir.flow_id = flow.to_string();
    mir.oper_nam = "synthetic".into();
    mir.exec_ver = "1.0".into();
    mir.user_txt = SYNTHETIC_NOTE.into();
    mir.facil_id = "SYNTH_FAB".into();
    mir.floor_id = "SYNTH_FLOOR".into();
    mir.famly_id = "CYPHER".into();
    mir.pkg_typ = if final_test { "QFN48".into() } else { String::new() };
    mir.spec_nam = "CYPHER01_SPEC".into();
    mir.spec_ver = "A".into();
    mir.setup_id = "SETUP01".into();
    mir.dsgn_rev = "A0".into();
    mir.serl_num = "SYNTH-0001".into();
}

/// The SDR of a TC-profile file: every equipment field filled in.
fn tc_sdr(sites: u8, final_test: bool, loadboard: Option<f64>) -> Sdr {
    let lb = loadboard.map_or("LB-01".to_string(), |b| format!("LB-{b}"));
    Sdr {
        head_num: 1,
        site_grp: 1,
        site_num: (1..=sites).collect(),
        hand_typ: if final_test { "HANDLER" } else { "PROBER" }.into(),
        hand_id: if final_test { "SYNTH-HDL01" } else { "SYNTH-PRB01" }.into(),
        card_typ: if final_test { "" } else { "PROBECARD" }.into(),
        card_id: if final_test { "" } else { "PC-01" }.into(),
        load_typ: "LOADBOARD".into(),
        load_id: lb.clone(),
        dib_typ: "DIB".into(),
        dib_id: lb,
        cont_typ: if final_test { "SOCKET" } else { "" }.into(),
        cont_id: if final_test { "SKT-01" } else { "" }.into(),
        ..Default::default()
    }
}

/// GDR.MIR_ADD and GDR.AUTOMATION of a TC-profile file.
fn tc_gdrs(w: &mut StdfWriter, step: &str, final_test: bool) -> Result<()> {
    gdr(
        w,
        "MIR_ADD",
        &[
            ("GUI_NAME", "stdf-cypher synthetic-sample".into()),
            ("GUI_VER", "1.0".into()),
            ("CONVERTER_NAME", "none".into()),
            ("CONVERTER_VER", "none".into()),
            ("TARGET_TEMP", "25".into()),
            ("OVERDRIVE", if final_test { "none".into() } else { "50".into() }),
        ],
    )?;
    gdr(
        w,
        "AUTOMATION",
        &[
            ("NAME", "synthetic".into()),
            ("VER", "1.0".into()),
            ("RECIPE", format!("CYPHER01_{step}")),
            ("STATUS", "OK".into()),
            ("INTERFACE", "none".into()),
            ("LOADER_API", "none".into()),
        ],
    )
}

#[derive(Debug, Clone)]
pub struct SampleSpec {
    pub lot_id: String,
    pub wafers: usize,
    /// die grid radius (dies across ≈ 2*radius)
    pub radius: i16,
    pub sites: u8,
    pub tests: usize,
    pub seed: u64,
    /// mean shift applied to tests (in sigma units) – use to create a "B" file
    pub shift: f64,
    /// extra noise multiplier for a "B" file
    pub noise: f64,
    /// fraction of dies that are outliers
    pub outlier_rate: f64,
    pub endian: Endian,
    /// final-test style (no wafer, no x/y)
    pub final_test: bool,
    /// independent re-measurement noise (sigma units) – same seed + this
    /// option simulates re-testing the same parts on another tester
    pub meas_noise: f64,
    /// per-test offsets in sigma units applied to every 3rd test (tester offset)
    pub tester_offset: f64,
    /// log prefixed units (uA, mV, MHz…) as the base unit (A, V, Hz) with the
    /// PTR RES_SCAL a tester uses to show them in the prefixed unit again
    pub base_units: bool,
    /// another draw of the re-measurement noise: same seed, meas_noise and a
    /// different meas_seed = the same parts on a further retest
    pub meas_seed: u64,
    /// limits move from wafer to wafer (a PAT-style program) and every PTR logs its own
    pub dynamic_limits: bool,
    /// loadboard (DIB) ID logged as test 5100 for every part
    pub loadboard: Option<f64>,
    /// share of parts whose loadboard result is missing
    pub loadboard_missing: f64,
    /// plant a retest pattern on these test numbers: some dies fail it just
    /// above the high limit (marginal), well above it (hard bad) or at a clamp
    /// value (extreme). On a retest (`meas_seed` ≠ 0) marginal and extreme
    /// dies mostly pass again; hard-bad dies never do. Each test picks its
    /// own dies.
    pub band_tests: Vec<u32>,
    /// extra parametric tests with these numbers (e.g. 1013, 2000), placed in
    /// test-number order among the generated ones
    pub extra_tests: Vec<u32>,
    /// the dies a band test would fail still pass these tests here, just
    /// inside the high limit: a run 1 where they are good, before a later
    /// file (with `band_tests`) fails them
    pub latent_tests: Vec<u32>,
    /// the STDF profile the file follows
    pub profile: Profile,
}

/// Uniform 0..1 from a die position and a salt (splitmix64), independent of
/// the random streams so a die keeps its role in every file.
fn die_u(wafer: usize, x: i16, y: i16, salt: u64) -> f64 {
    let mut z = (wafer as u64) << 40
        ^ ((x as u16 as u64) << 20)
        ^ (y as u16 as u64)
        ^ salt.wrapping_mul(0xD1B5_4A32_D192_ED03);
    z = z.wrapping_add(0x9E37_79B9_7F4A_7C15);
    z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    z ^= z >> 31;
    (z >> 11) as f64 / (1u64 << 53) as f64
}

